import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const repo=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const tmp=await mkdtemp(path.join(tmpdir(),'hooks-opencode-'));
const project=path.join(tmp,'project');await mkdir(project);
const py=process.env.TEST_PYTHON||'python';
const pid=execFileSync(py,['-c','import sys;sys.path.insert(0,sys.argv[1]);from funcionarios import id_projeto;print(id_projeto(sys.argv[2]))',repo,project],{encoding:'utf8'}).trim();
const binding=path.join(tmp,'binding.json');const db=path.join(tmp,'events.db');
await writeFile(binding,JSON.stringify({enabled:true,provider:'opencode',version:'1.18.35',project,project_id:pid,session_id:'s',origin:'fixture',agent:'Dev'}));
Object.assign(process.env,{OFFICE_HOOK_BINDING:binding,OFFICE_EMIT:path.join(repo,'hooks_providers.py'),OFFICE_BANCO:db,
  OFFICE_PYTHON:py,OFFICE_PROJETOS:project,OFFICE_AGENTE:'Dev',OFFICE_STREAM_OWNER:'plugin'});
const source=await readFile(path.join(repo,'opencode','office.js'),'utf8');
const {Office}=await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const hooks=await Office({directory:project});
await hooks.event({event:{type:'session.created',properties:{info:{id:'s'}}}});
await hooks['tool.execute.before']({tool:'read',sessionID:'s',callID:'read1'},{args:{path:'artificial.txt'}});
await hooks['tool.execute.after']({tool:'read',sessionID:'s',callID:'read1',args:{}},{});
await hooks.event({event:{type:'message.part.updated',properties:{part:{type:'tool',tool:'read',sessionID:'s',callID:'read1',state:{status:'error',error:'fixture failure'}}}}});
await hooks.event({event:{type:'session.idle',properties:{sessionID:'s'}}});
await hooks.event({event:{type:'session.deleted',properties:{info:{id:'s'}}}});
const read=()=>JSON.parse(execFileSync(py,['-c','import sys,sqlite3,json;c=sqlite3.connect(sys.argv[1]);print(json.dumps([json.loads(r[0]) for r in c.execute("SELECT dados FROM evento")]))',db],{encoding:'utf8'}));
const events=read();
assert.equal(events.length,6);
assert.deepEqual(events.map(e=>e.hook_fase),['start','tool_start','tool_end','tool_end','stop','end']);
assert.equal(events[3].ok,false);
assert.equal(events[3].hook_correction,true);
assert.ok(events.every(e=>e.sessao==='s'&&e.projeto_id===pid));
await hooks['tool.execute.after']({tool:'read',sessionID:'other',callID:'read1',args:{}},{});
assert.equal(read().length,6,'another session must not leak into the binding');
console.log('OpenCode native plugin receiver: lifecycle, failure, isolation OK');
